data = bytes([
    0x14,0x1c,0x02,0x21,0x22,0x6a,0x28,0x05,
    0x6b,0x29,0x05,0x3c,0x2f,0x34,0x05,0x38,
    0x2f,0x2e,0x05,0x34,0x6a,0x2e,0x05,0x29,
    0x69,0x39,0x2f,0x28,0x69,0x27
])

# Mencoba semua kemungkinan kunci dari 0 sampai 255
for key in range(256):
    dec = bytes(b ^ key for b in data)
    
    # Filter: hasil harus diawali 'NFX{' dan diakhiri '}'
    if dec.startswith(b'NFX{') and dec.endswith(b'}'):
        print(f"Key ditemukan: 0x{key:02x}")
        print(f"Flag: {dec.decode()}")
